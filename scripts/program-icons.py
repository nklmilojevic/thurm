#!/usr/bin/env python3
"""Print the brand marks for crates/thurm-config/src/programs/icons.rs.

Most programs show a category symbol; only a few get their own mark.

The pane icon renderer (macOS) parses absolute M/L/C/Z path data only, so this
rewrites Simple Icons (CC0) marks into that form: relative commands made absolute, H/V as
lines, quadratics and arcs as cubics.

    curl -sL https://registry.npmjs.org/simple-icons/-/simple-icons-16.33.0.tgz | tar xz -C /tmp
    uv run --with svgelements==1.9.6 scripts/program-icons.py /tmp/package > \
        crates/thurm-config/src/programs/icons.rs
"""

import re
import sys
from pathlib import Path

from svgelements import Arc, Close, CubicBezier, Line, Move, Path as SvgPath, QuadraticBezier

# Simple Icons slug for each icon id the program table uses.
ICONS = {
    "neovim": "neovim",
    "vim": "vim",
}


def num(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pt(p) -> str:
    return f"{num(p.x)} {num(p.y)}"


def flatten(d: str) -> str:
    out = []
    for seg in SvgPath(d):
        if isinstance(seg, Move):
            out.append(f"M{pt(seg.end)}")
        elif isinstance(seg, Close):
            out.append("Z")
        elif isinstance(seg, Line):
            out.append(f"L{pt(seg.end)}")
        elif isinstance(seg, CubicBezier):
            out.append(f"C{pt(seg.control1)} {pt(seg.control2)} {pt(seg.end)}")
        elif isinstance(seg, QuadraticBezier):
            c1 = seg.start + (seg.control - seg.start) * (2 / 3)
            c2 = seg.end + (seg.control - seg.end) * (2 / 3)
            out.append(f"C{pt(c1)} {pt(c2)} {pt(seg.end)}")
        elif isinstance(seg, Arc):
            for c in seg.as_cubic_curves():
                out.append(f"C{pt(c.control1)} {pt(c.control2)} {pt(c.end)}")
        else:
            raise SystemExit(f"unhandled segment {seg!r}")
    return "".join(out)


def main() -> None:
    package = Path(sys.argv[1])
    print("//! Generated by scripts/program-icons.py from Simple Icons (CC0): 24x24 marks as")
    print("//! absolute M/L/C/Z path data.")
    print()
    print("pub const ICONS: &[(&str, &str)] = &[")
    for id, slug in ICONS.items():
        svg = (package / "icons" / f"{slug}.svg").read_text()
        d = re.search(r'<path d="([^"]+)"', svg).group(1)
        print(f'    ("{id}", "{flatten(d)}"),')
    print("];")


if __name__ == "__main__":
    main()
